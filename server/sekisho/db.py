class _SqliteBackend:
    kind = "sqlite"

    def __init__(self, path: Path):
        self.path = Path(path)
        self.conn = sqlite3.connect(str(self.path), check_same_thread=False)
        self.conn.row_factory = sqlite3.Row
        self.conn.execute("PRAGMA journal_mode=WAL;")
        self.conn.execute("PRAGMA foreign_keys=ON;")
        self.conn.commit()

    @contextmanager
    def cursor(self) -> Iterator[Any]:
        """Serialized cursor access — the sqlite connection is shared across threads."""
        with _lock:
            cur = self.conn.cursor()
            try:
                yield cur
                self.conn.commit()
            finally:
                cur.close()

    def close(self) -> None:
        self.conn.close()

    def size_str(self) -> str:
        try:
            base = str(self.path)
            total = sum(Path(base + s).stat().st_size for s in ("", "-wal", "-shm")
                        if Path(base + s).exists())
        except Exception:
            return "?"
        return _human(total)


class _PgBackend:
    kind = "postgres"

    def __init__(self, url: str):
        try:
            import psycopg  # noqa: F401
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool
        except ImportError as e:  # pragma: no cover - deployment error
            raise ConfigError("DATABASE_URL is set but psycopg/psycopg-pool are not installed") from e
        import os
        # prepare_threshold=None: never server-side prepare, so PgBouncer/Neon
        # pooled connections (transaction mode) are safe.
        self.pool = ConnectionPool(
            url,
            min_size=0,
            max_size=int(os.environ.get("SEKISHO_PG_POOL_MAX", "4") or 4),
            kwargs={"row_factory": dict_row, "prepare_threshold": None, "autocommit": False,
                    "connect_timeout": 10},
            check=ConnectionPool.check_connection,
            max_idle=120,
            max_lifetime=1800,
            timeout=15,
            open=True,
            name="sekisho",
        )

    @contextmanager
    def cursor(self) -> Iterator[Any]:
        from psycopg import pq
        with self.pool.connection() as conn:
            raw = conn.cursor()
            cur = _PgCursor(raw)
            try:
                yield cur
            except BaseException:
                # Mirror the SQLite semantics: work done before a non-DB exception
                # (e.g. AccountError after bumping failed_count) is still committed;
                # a failed SQL statement rolls the transaction back.
                if conn.info.transaction_status == pq.TransactionStatus.INERROR:
                    conn.rollback()
                else:
                    conn.commit()
                raise
            finally:
                raw.close()
            conn.commit()

    def close(self) -> None:
        self.pool.close()

    def size_str(self) -> str:
        try:
            with self.cursor() as cur:
                row = cur.execute("SELECT pg_database_size(current_database()) AS s").fetchone()
            return _human(int(row["s"]))
        except Exception:
            return "?"


def _human(total: float) -> str:
    size = float(total)
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024 or unit == "GB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1024.0
    return f"{size:.1f} GB"


_backend: _SqliteBackend | _PgBackend | None = None


def backend_kind() -> str:
    return _backend.kind if _backend else "uninitialized"


def is_postgres() -> bool:
    return _backend is not None and _backend.kind == "postgres"


def size_str() -> str:
    return _backend.size_str() if _backend else "?"



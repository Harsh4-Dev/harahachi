def init_db(db_path: Path | None = None, *, database_url: str | None = None) -> None:
    """Open the store and run migrations.

    * ``database_url`` given            -> Postgres
    * ``db_path`` given                 -> SQLite at that path (tests, tools)
    * neither                           -> from config (DATABASE_URL, else SQLite)
    """
    global _backend
    if database_url is None and db_path is None:
        from .config import config
        database_url = config.database_url
        if not database_url:
            if config.on_vercel:
                raise ConfigError(
                    "DATABASE_URL is not set. On Vercel the filesystem is read-only and "
                    "per-instance, so Sekisho needs Postgres (Neon via the Vercel Marketplace)."
                )
            db_path = config.db_file
    if database_url:
        _backend = _PgBackend(database_url)
    else:
        # NOTE: schema creation is owned by migrate(). Running executescript(SCHEMA)
        # first would fail on a legacy v1 DB (indexes on meals/workouts(user_id)
        # while the legacy tables still key by device_id). migrate() renames
        # legacy tables aside FIRST, then creates the current schema.
        _backend = _SqliteBackend(Path(db_path))
    migrate()


def init_from_config() -> None:
    init_db()


def ensure_init() -> None:
    """Lazily initialize from config (serverless cold start, first request)."""
    if _backend is None:
        with _init_lock:
            if _backend is None:
                init_db()


_init_lock = threading.Lock()


@contextmanager
def cursor() -> Iterator[Any]:
    if _backend is None:
        ensure_init()
    assert _backend is not None, "db not initialized"
    with _backend.cursor() as cur:
        yield cur


def get_setting(key: str, default: str | None = None) -> str | None:
    with cursor() as cur:
        row = cur.execute("SELECT value FROM settings WHERE key=?", (key,)).fetchone()
    return row["value"] if row else default


def set_setting(key: str, value: str | None) -> None:
    with cursor() as cur:
        cur.execute(
            "INSERT INTO settings (key, value) VALUES (?,?) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (key, value),
        )


def delete_setting(key: str) -> None:
    with cursor() as cur:
        cur.execute("DELETE FROM settings WHERE key=?", (key,))


def close_db() -> None:
    global _backend
    if _backend is not None:
        _backend.close()
        _backend = None

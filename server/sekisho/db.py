"""Storage layer for Sekisho: SQLite (default) or Postgres (``DATABASE_URL``).

v1 keyed all app data per ``device_id``. v2 introduces user **accounts**: the
data (profiles/meals/workouts/push) is now keyed by ``user_id`` while the device
key remains the transport credential. ``devices.active_user_id`` records which
user a paired device is currently logged in as.

v4 (Vercel): one thin adapter so the same SQL runs on both engines without an
ORM rewrite. Callers keep writing SQLite-flavoured SQL (``?`` placeholders,
``ON CONFLICT(...) DO UPDATE ... excluded.x``); on Postgres the adapter

* translates ``?`` -> ``%s`` (and escapes literal ``%``),
* emulates ``cursor.lastrowid`` by appending ``RETURNING id`` to INSERTs into
  tables that have an identity ``id``,
* creates the schema with ``AUTOINCREMENT`` -> ``GENERATED BY DEFAULT AS
  IDENTITY`` and ``REAL`` -> ``DOUBLE PRECISION``,
* replaces ``PRAGMA table_info`` / ``sqlite_master`` with ``information_schema``,
* returns dict rows (``row["col"]``, ``row.keys()``, ``dict(row)`` all work, the
  same surface code uses on ``sqlite3.Row``).

``migrate()`` runs on boot (and lazily on first use in serverless): it adds the
v2..v4 columns/tables idempotently and, for a legacy v1 SQLite DB, auto-creates
a user per device and moves that device's data onto it.
"""

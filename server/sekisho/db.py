# Tables whose primary key is an auto-generated integer ``id`` (lastrowid emulation
# and sequence fix-ups after a data migration).
IDENTITY_TABLES = frozenset({
    "users", "meals", "workouts", "request_log", "backends", "push_subscriptions", "weights",
    "llm_calls", "ops_audit",
})


# ---------------------------------------------------------------------------
# SQL translation (SQLite dialect -> Postgres)
# ---------------------------------------------------------------------------
_INSERT_RE = re.compile(r"^\s*INSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)", re.IGNORECASE)


@lru_cache(maxsize=1024)
def _translate(sql: str) -> tuple[str, bool]:
    """Return (postgres_sql, wants_lastrowid)."""
    out: list[str] = []
    quote: str | None = None
    for ch in sql:
        if quote:
            out.append("%%" if ch == "%" else ch)
            if ch == quote:
                quote = None
            continue
        if ch in ("'", '"'):
            quote = ch
            out.append(ch)
        elif ch == "?":
            out.append("%s")
        elif ch == "%":
            out.append("%%")
        else:
            out.append(ch)
    q = "".join(out)
    wants_id = False
    m = _INSERT_RE.match(q)
    if m and m.group(1).lower() in IDENTITY_TABLES and " returning " not in q.lower():
        q = q.rstrip().rstrip(";") + " RETURNING id"
        wants_id = True
    return q, wants_id


def pg_schema_statements() -> list[str]:
    """SCHEMA translated to Postgres DDL, one statement per item."""
    lines = [ln for ln in SCHEMA.splitlines() if not ln.strip().startswith("--")]
    ddl = "\n".join(lines)
    ddl = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
                 "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", ddl, flags=re.IGNORECASE)
    ddl = re.sub(r"\bREAL\b", "DOUBLE PRECISION", ddl)
    return [s.strip() for s in ddl.split(";") if s.strip()]


def _coerce_params(params: Any) -> Any:
    if params is None:
        return ()
    if isinstance(params, dict):
        return params
    return tuple(int(p) if isinstance(p, bool) else p for p in params)


class _PgCursor:
    """sqlite3.Cursor-shaped wrapper over a psycopg cursor (dict rows)."""

    def __init__(self, cur):
        self._cur = cur
        self.lastrowid: int | None = None

    def execute(self, sql: str, params: Any = ()):
        q, wants_id = _translate(sql)
        self._cur.execute(q, _coerce_params(params))
        if wants_id:
            row = self._cur.fetchone()
            self.lastrowid = row["id"] if row else None
        return self

    def executemany(self, sql: str, seq):
        q, _ = _translate(sql)
        q = re.sub(r"\s+RETURNING id$", "", q)
        self._cur.executemany(q, [_coerce_params(p) for p in seq])
        return self

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur.fetchall())

    @property
    def rowcount(self) -> int:
        return self._cur.rowcount

    def close(self) -> None:
        self._cur.close()


